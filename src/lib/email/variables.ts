/**
 * Template variable definitions and substitution.
 *
 * This module is deliberately isomorphic — it is imported by both the admin
 * email-templates editor (browser) and the tRPC routers that actually send mail
 * (server). It must therefore stay free of Prisma, node builtins, and `$env`.
 * Anything that touches transport or environment belongs in `$lib/server/email.ts`.
 */

/**
 * The single source of truth for which `{{variables}}` exist.
 *
 * A variable listed here MUST be produced by `buildTemplateVars`, otherwise the
 * editor advertises a placeholder that arrives in a hacker's inbox unsubstituted.
 * `variables.test.ts` asserts the two stay in sync.
 *
 * `sample` mirrors the real output format (`Date.toLocaleDateString()`), not a
 * prettier one — the preview is only useful if it shows what actually sends.
 */
export const TEMPLATE_VARIABLES = [
	{ key: 'name', label: "Hacker's full name", sample: 'Sarah Chen' },
	{ key: 'hackathon_start', label: 'Hackathon start date', sample: '4/15/2026' },
	{ key: 'rsvp_deadline', label: 'RSVP deadline', sample: '4/1/2026' },
	{
		key: 'check_in_pass',
		label: 'Check-in pass',
		sample: '[QR code + wallet buttons]',
		hint:
			"Inserts the recipient's QR code, their RC- code, and Add to Apple/Google " +
			'Wallet buttons. Confirmed attendees only; the wallet buttons appear once ' +
			'the RSVP deadline has passed.',
		/**
		 * Substitutes a block of pre-built HTML rather than a piece of text, so it
		 * must not be escaped on its way into the message body. Everything inside
		 * that block is generated by `$lib/server/wallet/email-block`, which escapes
		 * the one user-controlled value it embeds (the hacker's own name).
		 *
		 * Nothing else may be marked `raw` without the same guarantee — an
		 * unescaped value that an applicant can set is a script tag in an inbox.
		 */
		raw: true
	}
] as const;

export type TemplateVariableKey = (typeof TEMPLATE_VARIABLES)[number]['key'];

export const VARIABLE_KEYS: readonly string[] = TEMPLATE_VARIABLES.map((v) => v.key);

/**
 * Variables whose value is markup, not text.
 *
 * Two consequences: they skip HTML escaping in a body, and they are dropped
 * entirely from a subject — the editor's chips can insert into either field, and
 * a subject line is plain text, so a block variable there would otherwise mail
 * out a subject full of raw `<table>` markup.
 */
export const RAW_VARIABLE_KEYS: ReadonlySet<string> = new Set(
	TEMPLATE_VARIABLES.filter((v) => 'raw' in v && v.raw).map((v) => v.key)
);

/** Placeholder values used by the admin preview pane. */
export const SAMPLE_VARS: Record<string, string> = Object.fromEntries(
	TEMPLATE_VARIABLES.map((v) => [v.key, v.sample])
);

const VARIABLE_PATTERN = /\{\{(\w+)\}\}/g;

/** Escape the five HTML-significant characters. */
function escapeHtml(value: string): string {
	return value
		.replace(/&/g, '&amp;')
		.replace(/</g, '&lt;')
		.replace(/>/g, '&gt;')
		.replace(/"/g, '&quot;')
		.replace(/'/g, '&#39;');
}

/**
 * Replace `{{key}}` with `vars[key]`. Unknown keys are left literal.
 *
 * `escapeValues` HTML-escapes each substituted value and is used for the *body* of an
 * outbound email, which is rendered through `marked` into HTML. Variable values include
 * `name`, which is user-controlled (an applicant can set it via a linked question), so
 * without escaping a name like `<script>…` or `<a href=…>` would inject live markup into
 * the message. Subjects and the admin preview pass this false — a subject is plain text,
 * and the preview escapes segments itself via Svelte.
 */
export function substituteVariables(
	template: string,
	vars: Record<string, string>,
	{
		escapeValues = false,
		dropRawValues = false
	}: { escapeValues?: boolean; dropRawValues?: boolean } = {}
): string {
	return template.replace(VARIABLE_PATTERN, (_, key) => {
		const value = vars[key];
		if (value === undefined) return `{{${key}}}`;

		if (RAW_VARIABLE_KEYS.has(key)) {
			// A markup block. Dropped from subjects, and never escaped in a body —
			// escaping it would mail the hacker the HTML source of their own QR code.
			return dropRawValues ? '' : value;
		}
		return escapeValues ? escapeHtml(value) : value;
	});
}

export type TemplateSegment =
	| { type: 'text'; value: string }
	/** `value` is the substituted sample; the source text was `{{key}}`. */
	| { type: 'known'; value: string; key: string }
	/** No value to substitute, so `value` is the literal `{{key}}`. */
	| { type: 'unknown'; value: string; key: string };

/**
 * Split a template into renderable segments so the preview can mark up variables
 * without `{@html}` — Svelte escapes each segment's text for us.
 */
export function tokenizeTemplate(
	template: string,
	vars: Record<string, string> = SAMPLE_VARS
): TemplateSegment[] {
	const segments: TemplateSegment[] = [];
	let last = 0;

	// Fresh lastIndex per call: VARIABLE_PATTERN is global and module-scoped.
	VARIABLE_PATTERN.lastIndex = 0;
	let match: RegExpExecArray | null;

	while ((match = VARIABLE_PATTERN.exec(template)) !== null) {
		if (match.index > last) {
			segments.push({ type: 'text', value: template.slice(last, match.index) });
		}
		const key = match[1];
		const value = vars[key];
		segments.push(
			value === undefined
				? { type: 'unknown', value: `{{${key}}}`, key }
				: { type: 'known', value, key }
		);
		last = match.index + match[0].length;
	}

	if (last < template.length) {
		segments.push({ type: 'text', value: template.slice(last) });
	}

	return segments;
}

/**
 * Build the substitution map for a real send.
 *
 * Structurally typed so callers can pass a Prisma `User`/`Settings` row without
 * this module importing Prisma.
 */
export function buildTemplateVars(
	user: { name: string },
	settings: { hackathonStartDate: Date; RSVPDeadline: Date },
	/**
	 * The pre-rendered check-in block, from `$lib/server/wallet/email-block`.
	 *
	 * Passed in rather than built here because producing it needs Prisma, the QR
	 * encoder, and an inline image attachment, none of which may enter this module.
	 * Defaults to empty, which is also the correct value for a recipient who has
	 * no pass to show — an applicant who never confirmed gets the rest of the
	 * email with the block silently absent, rather than a gap where it should be.
	 */
	checkInPass = ''
): Record<string, string> {
	return {
		name: user.name,
		hackathon_start: settings.hackathonStartDate.toLocaleDateString(),
		rsvp_deadline: settings.RSVPDeadline.toLocaleDateString(),
		check_in_pass: checkInPass
	};
}
