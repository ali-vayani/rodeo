/**
 * Bytes behind the seeded FILE answers.
 *
 * A FILE response row on its own is a broken answer: the admissions pane shows a
 * filename, and the viewer behind it 404s because nothing was ever stored. So the seed
 * writes a real PDF for every file answer it generates.
 *
 * Written straight to `.uploads/` via the local backend rather than through
 * `$lib/server/storage`, which reads `$env` and cannot be imported under tsx. That is
 * the same backend a developer with no bucket configured gets — and the seed refuses
 * non-local databases anyway, so it is the only one that can be correct here.
 */

import { applicationFileKey } from '../src/lib/application/files';
import { putObject, UPLOADS_ROOT } from '../src/lib/server/storage-local';

const REQUIRED_S3_VARS = ['AWS_REGION', 'S3_BUCKET', 'AWS_ACCESS_KEY_ID', 'AWS_SECRET_ACCESS_KEY'];

/** Escape the three characters that end a PDF string literal early. */
function pdfString(text: string): string {
	return text.replace(/[\\()]/g, (c) => `\\${c}`);
}

/**
 * A one-page PDF naming the applicant.
 *
 * Hand-assembled rather than pulled from a library: a few kilobytes a viewer will
 * render is the whole requirement. Everything stays latin1 — one byte per character —
 * because the xref offsets are byte counts of what came before them.
 *
 * Inputs:
 * - name: string — drawn as the heading
 * - heading: string — the line beneath it, e.g. the question title
 *
 * Outputs:
 * - Buffer — the complete PDF
 */
export function samplePdf(name: string, heading: string): Buffer {
	const lines = [
		`BT /F1 24 Tf 72 700 Td (${pdfString(name)}) Tj ET`,
		`BT /F1 12 Tf 72 670 Td (${pdfString(heading)}) Tj ET`,
		`BT /F1 10 Tf 72 640 Td (Generated by the Rodeo seed script. Not a real document.) Tj ET`
	].join('\n');

	const objects = [
		'<< /Type /Catalog /Pages 2 0 R >>',
		'<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
		'<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] ' +
			'/Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>',
		'<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
		`<< /Length ${lines.length} >>\nstream\n${lines}\nendstream`
	];

	let pdf = '%PDF-1.4\n';
	const offsets: number[] = [];
	objects.forEach((body, i) => {
		offsets.push(pdf.length);
		pdf += `${i + 1} 0 obj\n${body}\nendobj\n`;
	});

	const xrefStart = pdf.length;
	pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
	for (const offset of offsets) {
		pdf += `${String(offset).padStart(10, '0')} 00000 n \n`;
	}
	pdf += `trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\nstartxref\n${xrefStart}\n%%EOF\n`;

	return Buffer.from(pdf, 'latin1');
}

export type SeededFile = { userId: string; questionId: string; name: string; heading: string };

/**
 * Write a PDF for each seeded file answer.
 *
 * Inputs:
 * - files: SeededFile[] — one per FILE response row, already in the database
 *
 * Outputs:
 * - number — how many were written. Zero when a bucket is configured, since these
 *   would go to disk where nothing would read them.
 *
 * Side effects:
 * - Writes each PDF to the local uploads directory, and logs the outcome.
 */
export async function writeSeedFiles(files: SeededFile[]): Promise<number> {
	if (!files.length) return 0;

	// A configured bucket means the app reads from S3 and would 404 on every one of
	// these. Say so rather than writing files nothing will ever open.
	if (REQUIRED_S3_VARS.every((name) => process.env[name])) {
		console.log(
			`  ! ${files.length} file answer(s) written without bytes: S3 is configured, and this\n` +
				'    script only writes to the local uploads directory. Unset S3_BUCKET to seed them.'
		);
		return 0;
	}

	for (const file of files) {
		await putObject(
			applicationFileKey(file.userId, file.questionId),
			samplePdf(file.name, file.heading)
		);
	}

	console.log(`  ✓ ${files.length} sample PDF(s) under ${UPLOADS_ROOT}`);
	return files.length;
}
